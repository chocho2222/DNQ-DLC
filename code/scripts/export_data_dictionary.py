def read_header(path):
    with path.open(newline="", encoding="utf-8") as handle:
        reader = csv.reader(handle)
        return next(reader)


def describe_field(field):
    return FIELD_DEFS.get(field, ("No field definition registered.", "unknown", "unknown"))


def build_report(root):
    freshness_csv = root / "materials" / "CROSS_REPORT_FRESHNESS_AUDIT.csv"
    if not freshness_csv.exists():
        freshness_csv.write_text(",".join(["check_id", "category", "status", "expected", "observed", "file", "location", "note"]) + "\n", encoding="utf-8")
    tables = []
    rows = []
    missing_files = []
    missing_definitions = []
    for spec in TABLES:
        path = root / spec["path"]
        if not path.exists():
            missing_files.append(spec["path"])
            columns = []
        else:
            columns = read_header(path)
        tables.append({**spec, "exists": path.exists(), "columns": columns, "column_count": len(columns)})
        for column in columns:
            meaning, dtype, units = describe_field(column)
            if dtype == "unknown":
                missing_definitions.append({"table": spec["path"], "field": column})
            rows.append(
                {
                    "table": spec["path"],
                    "title": spec["title"],
                    "field": column,
                    "meaning": meaning,
                    "type": dtype,
                    "units": units,
                    "source": spec["source"],
                    "purpose": spec["purpose"],
                }
            )
    return {
        "root": str(root),
        "tables": tables,
        "fields": rows,
        "summary": {
            "table_count": len(tables),
            "field_count": len(rows),
            "missing_files": missing_files,
            "missing_definition_count": len(missing_definitions),
            "complete": not missing_files and not missing_definitions,
        },
        "missing_definitions": missing_definitions,
        "interpretation": (
            "This package-level data dictionary maps key machine-readable tables to field meanings, "
            "types, units, sources, and intended use. It complements the Figure 3 source-data dictionary."
        ),
    }


def write_csv(report, path):
    fields = ["table", "title", "field", "meaning", "type", "units", "source", "purpose"]
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for row in report["fields"]:
            writer.writerow({key: row[key] for key in fields})


def write_markdown(report, path):
    lines = [
        "# Data Dictionary",
        "",
        report["interpretation"],
        "",
        "## Summary",
        "",
        f"- Tables: {report['summary']['table_count']}",
        f"- Fields: {report['summary']['field_count']}",
        f"- Complete: {report['summary']['complete']}",
        f"- Missing files: {len(report['summary']['missing_files'])}",
        f"- Missing field definitions: {report['summary']['missing_definition_count']}",
        "",
        "## Tables",
        "",
        "| table | title | columns | source | purpose |",
        "|---|---|---:|---|---|",
    ]
    for table in report["tables"]:
        lines.append(
            f"| `{table['path']}` | {table['title']} | {table['column_count']} | `{table['source']}` | {table['purpose']} |"
        )
    lines.extend(["", "## Fields", "", "| table | field | type | units | meaning |", "|---|---|---|---|---|"])
    for row in report["fields"]:
        lines.append(f"| `{row['table']}` | `{row['field']}` | {row['type']} | {row['units']} | {row['meaning']} |")
    if report["missing_definitions"]:
        lines.extend(["", "## Missing Definitions", ""])
        for item in report["missing_definitions"]:
            lines.append(f"- `{item['table']}`: `{item['field']}`")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description="Export package-level data dictionary.")
    parser.add_argument("--root", default="outputs/paper_multicar_overtake_20260618")
    args = parser.parse_args()
    root = Path(args.root)
    materials = root / "materials"
    materials.mkdir(parents=True, exist_ok=True)
    report = build_report(root)
    out_json = materials / "DATA_DICTIONARY.json"
    out_md = materials / "DATA_DICTIONARY.md"
    out_csv = materials / "DATA_DICTIONARY.csv"
    out_json.write_text(json.dumps(report, indent=2), encoding="utf-8")
    write_markdown(report, out_md)
    write_csv(report, out_csv)
    print(json.dumps({"json": str(out_json), "markdown": str(out_md), "csv": str(out_csv), "complete": report["summary"]["complete"]}, indent=2))


if __name__ == "__main__":
    main()
